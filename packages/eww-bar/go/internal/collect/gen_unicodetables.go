//go:build ignore

// Command gen_unicodetables writes unicodetables.go: the Unicode data the Python
// ports in this package read, taken from the running toolchain's unicode package.
// It refuses to run unless that package is at Unicode 15.0.0.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"unicode"
)

const frozenVersion = "15.0.0"

// caseRun and mapCase must stay in step with their twins in pystr.go.
type caseRun struct{ Lo, Hi, Stride, Delta rune }

func mapCase(runs []caseRun, r rune) rune {
	i := sort.Search(len(runs), func(i int) bool { return runs[i].Hi >= r })
	if i < len(runs) && r >= runs[i].Lo && (r-runs[i].Lo)%runs[i].Stride == 0 {
		return r + runs[i].Delta
	}
	return r
}

func isCased(r rune) bool {
	return unicode.IsUpper(r) || unicode.IsLower(r) || unicode.IsTitle(r)
}

func main() {
	if unicode.Version != frozenVersion {
		log.Fatalf("unicode.Version is %s, want %s", unicode.Version, frozenVersion)
	}

	cased := rangeTable(isCased)
	lower := caseRuns(unicode.ToLower)
	title := caseRuns(unicode.ToTitle)

	for r := rune(0); r <= unicode.MaxRune; r++ {
		if unicode.Is(cased, r) != isCased(r) {
			log.Fatalf("pyCased disagrees with the unicode package at U+%04X", r)
		}
		if got, want := mapCase(lower, r), unicode.ToLower(r); got != want {
			log.Fatalf("pyLowerRuns maps U+%04X to U+%04X, want U+%04X", r, got, want)
		}
		if got, want := mapCase(title, r), unicode.ToTitle(r); got != want {
			log.Fatalf("pyTitleRuns maps U+%04X to U+%04X, want U+%04X", r, got, want)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_unicodetables.go from Unicode %s; DO NOT EDIT.\n\n", unicode.Version)
	b.WriteString("//go:generate go run gen_unicodetables.go\n\n")
	b.WriteString("package collect\n\nimport \"unicode\"\n\n")
	writeTable(&b, "pyNd", "unicode.Nd", unicode.Nd)
	writeTable(&b, "pyCased", "every code point unicode.IsUpper, IsLower or IsTitle accepts", cased)
	writeRuns(&b, "pyLowerRuns", "unicode.ToLower", lower)
	writeRuns(&b, "pyTitleRuns", "unicode.ToTitle", title)

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("unicodetables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// caseRuns compresses mapping into runs of code points, Stride apart, that all
// move by the same Delta. Code points the mapping leaves alone are not listed.
func caseRuns(mapping func(rune) rune) []caseRun {
	var runs []caseRun
	for r := rune(0); r <= unicode.MaxRune; r++ {
		delta := mapping(r) - r
		if delta == 0 {
			continue
		}
		if n := len(runs); n > 0 {
			last := &runs[n-1]
			gap := r - last.Hi
			single := last.Lo == last.Hi
			if last.Delta == delta && (gap == last.Stride || (single && gap == 2)) {
				if single {
					last.Stride = gap
				}
				last.Hi = r
				continue
			}
		}
		runs = append(runs, caseRun{r, r, 1, delta})
	}
	return runs
}

// rangeTable builds a stride-1 table of the code points in reports true for. No
// range crosses U+FFFF, so each falls wholly in R16 or R32.
func rangeTable(in func(rune) bool) *unicode.RangeTable {
	t := &unicode.RangeTable{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !in(r) {
			continue
		}
		lo := r
		for r < unicode.MaxRune && r != 0xFFFF && in(r+1) {
			r++
		}
		if lo <= 0xFFFF {
			t.R16 = append(t.R16, unicode.Range16{Lo: uint16(lo), Hi: uint16(r), Stride: 1})
			if r <= unicode.MaxLatin1 {
				t.LatinOffset++
			}
		} else {
			t.R32 = append(t.R32, unicode.Range32{Lo: uint32(lo), Hi: uint32(r), Stride: 1})
		}
	}
	return t
}

func writeTable(b *bytes.Buffer, name, doc string, t *unicode.RangeTable) {
	fmt.Fprintf(b, "// %s is %s.\nvar %s = &unicode.RangeTable{\n", name, doc, name)
	if len(t.R16) > 0 {
		b.WriteString("R16: []unicode.Range16{\n")
		for _, rg := range t.R16 {
			fmt.Fprintf(b, "{0x%04X, 0x%04X, %d},\n", rg.Lo, rg.Hi, rg.Stride)
		}
		b.WriteString("},\n")
	}
	if len(t.R32) > 0 {
		b.WriteString("R32: []unicode.Range32{\n")
		for _, rg := range t.R32 {
			fmt.Fprintf(b, "{0x%05X, 0x%05X, %d},\n", rg.Lo, rg.Hi, rg.Stride)
		}
		b.WriteString("},\n")
	}
	if t.LatinOffset > 0 {
		fmt.Fprintf(b, "LatinOffset: %d,\n", t.LatinOffset)
	}
	b.WriteString("}\n\n")
}

func writeRuns(b *bytes.Buffer, name, doc string, runs []caseRun) {
	fmt.Fprintf(b, "// %s is %s as caseRun entries.\nvar %s = []caseRun{\n", name, doc, name)
	for _, c := range runs {
		fmt.Fprintf(b, "{0x%04X, 0x%04X, %d, %d},\n", c.Lo, c.Hi, c.Stride, c.Delta)
	}
	b.WriteString("}\n\n")
}
